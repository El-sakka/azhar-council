-- Initial schema for the Supreme Council of Al-Azhar documents & registers database.

-- Normalises Arabic text for tolerant searching (hamza/alef forms, taa marbuta, alef maqsura, tatweel).
CREATE OR REPLACE FUNCTION normalize_ar(input TEXT) RETURNS TEXT
    LANGUAGE sql IMMUTABLE PARALLEL SAFE AS
$$
SELECT lower(translate(coalesce(input, ''), 'أإآٱىةؤئـ', 'اااايهءء'))
$$;

CREATE TABLE app_user
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(200),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Hierarchical subject classification (main subject -> sub subject -> detailed subject).
CREATE TABLE subject
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(20)  NOT NULL UNIQUE,
    name       VARCHAR(200) NOT NULL,
    parent_id  BIGINT REFERENCES subject (id) ON DELETE RESTRICT,
    level      SMALLINT     NOT NULL CHECK (level BETWEEN 1 AND 3),
    sort_order INT          NOT NULL
);
CREATE INDEX idx_subject_parent ON subject (parent_id);

-- Inventory list of the council's files (قائمة حصر الملفات).
CREATE TABLE archive_file
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial_no          INT          NOT NULL UNIQUE,
    file_number        VARCHAR(50),
    reference_code     VARCHAR(100) NOT NULL UNIQUE,
    title              VARCHAR(500) NOT NULL,
    cover_color        VARCHAR(100),
    file_size          VARCHAR(100),
    start_date         VARCHAR(50),
    end_date           VARCHAR(50),
    year_from          SMALLINT,
    year_to            SMALLINT,
    sheet_count        INT CHECK (sheet_count >= 0),
    language           VARCHAR(200),
    subject_content    TEXT,
    physical_condition TEXT,
    notes              TEXT,
    CONSTRAINT chk_file_years CHECK (year_from IS NULL OR year_to IS NULL OR year_from <= year_to)
);
CREATE INDEX idx_file_years ON archive_file (year_from, year_to);

-- Inventory list of the council's registers (قائمة حصر السجلات).
CREATE TABLE archive_register
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial_no          INT          NOT NULL UNIQUE,
    register_number    VARCHAR(50),
    reference_code     VARCHAR(100) NOT NULL UNIQUE,
    title              VARCHAR(500) NOT NULL,
    sub_unit_name      VARCHAR(200),
    direction          VARCHAR(200),
    start_date         VARCHAR(50),
    end_date           VARCHAR(50),
    year_from          SMALLINT,
    year_to            SMALLINT,
    subjects_text      TEXT,
    written_sheets     INT CHECK (written_sheets >= 0),
    blank_sheets       INT CHECK (blank_sheets >= 0),
    language           VARCHAR(200),
    script_type        VARCHAR(100),
    length_cm          INT CHECK (length_cm > 0),
    width_cm           INT CHECK (width_cm > 0),
    physical_condition TEXT,
    CONSTRAINT chk_register_years CHECK (year_from IS NULL OR year_to IS NULL OR year_from <= year_to)
);
CREATE INDEX idx_register_years ON archive_register (year_from, year_to);

-- One row per line of each subject table ("كل موضوع له جدول خاص به").
-- Keeps the wording used in the subject table and links to the inventory row it describes.
CREATE TABLE subject_entry
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id          BIGINT       NOT NULL REFERENCES subject (id) ON DELETE CASCADE,
    entry_type          VARCHAR(10)  NOT NULL CHECK (entry_type IN ('FILE', 'REGISTER')),
    serial_no           INT          NOT NULL,
    item_number         VARCHAR(50),
    reference_code      VARCHAR(100),
    title               VARCHAR(500) NOT NULL,
    date_text           VARCHAR(100),
    year_from           SMALLINT,
    year_to             SMALLINT,
    subject_content     TEXT,
    archive_file_id     BIGINT REFERENCES archive_file (id) ON DELETE SET NULL,
    archive_register_id BIGINT REFERENCES archive_register (id) ON DELETE SET NULL,
    CONSTRAINT chk_entry_link CHECK (
        (entry_type = 'FILE' AND archive_register_id IS NULL) OR
        (entry_type = 'REGISTER' AND archive_file_id IS NULL))
);
CREATE INDEX idx_entry_subject ON subject_entry (subject_id, entry_type);
CREATE INDEX idx_entry_file ON subject_entry (archive_file_id);
CREATE INDEX idx_entry_register ON subject_entry (archive_register_id);
